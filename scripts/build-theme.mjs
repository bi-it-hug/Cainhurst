// ── JSONC helpers ────────────────────────────────────────────────────────────
const stripComments = s => s.replace(/("(?:\\.|[^"\\])*")|\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, (m, str) => str ?? '');
const parseJsonc = s => JSON.parse(stripComments(s).replace(/,(\s*[}\]])/g, '$1'));

// Index of the brace that closes the object opened at `open`, skipping strings and comments.
function closingBrace(text, open) {
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    const c = text[i];
    if (c === '"') { for (i++; text[i] !== '"'; i++) if (text[i] === '\\') i++; }
    else if (c === '/' && text[i + 1] === '/') i = text.indexOf('\n', i);
    else if (c === '/' && text[i + 1] === '*') i = text.indexOf('*/', i) + 1;
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return i;
  }
  throw new Error('Unbalanced braces in "colors"');
}

// ── Checks ───────────────────────────────────────────────────────────────────
const official = [...new Set(readFileSync(KEYS, 'utf8').split('\n').filter(l => l && !l.startsWith('#')))];
const colors = Object.assign({}, ...Object.values(sections));
const missing = official.filter(k => !(k in colors) && !UNSET.has(k));
const unknown = Object.keys(colors).filter(k => !official.includes(k));
const dupes = Object.values(sections).flatMap(Object.keys).filter((k, i, all) => all.indexOf(k) !== i);
const invalid = Object.entries(colors).filter(([, v]) => !/^#([0-9a-f]{6}|[0-9a-f]{8})$/i.test(v));
const unsorted = Object.entries(sections).filter(([, e]) => {
  const keys = Object.keys(e);
  return keys.some((k, i) => i && keys[i - 1].localeCompare(k, 'en', { sensitivity: 'base' }) > 0);
});

console.log(`colors: ${Object.keys(colors).length} of ${official.length} official, intentionally unset: ${[...UNSET].join(', ')}`);
if (missing.length) console.log('NOT COVERED:', missing.join(', '));
if (unknown.length) console.log('Not in the official list (typo or removed key?):', unknown.join(', '));
if (dupes.length) console.log('Defined in two groups:', dupes.join(', '));
if (invalid.length) console.log('Not a hex color:', invalid.map(([k, v]) => `${k}=${v}`).join(', '));
if (unsorted.length) console.log('Groups not sorted A–Z:', unsorted.map(([s]) => s).join(', '));
const failed = missing.length || unknown.length || dupes.length || invalid.length;
if (process.argv.includes('--check') || failed) process.exit(failed ? 1 : 0);

